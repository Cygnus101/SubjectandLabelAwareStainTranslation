"""
Assemble a YOLO segmentation dataset from OME slides by downsampling them to PNG
and pairing with label files generated by `generate_yolo_masks.py`.

Outputs
-------
<output_root>/
    images/{train,val}/{type}/<slide>.png
    labels/{train,val}/{type}/<slide>.txt
    data.yaml                                  (Ultralytics-style config)

Example
-------
python -m src.utils.prepare_yolo_dataset \\
    --data-root /Volumes/Expansion/BiopsyExtractedSet \\
    --metadata metadata.csv \\
    --labels-root outputs/yolo_masks/labels \\
    --output-root outputs/yolo_dataset \\
    --downsample 0.1

Then train (Ultralytics v8):
    yolo segment train data=outputs/yolo_dataset/data.yaml model=yolov8n-seg.pt
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, Tuple

import numpy as np
import pandas as pd
from PIL import Image
import tifffile
from tqdm import tqdm

from .generate_yolo_masks import _clean_stem, _type_folder, build_masks


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-root",
        type=Path,
        required=True,
        help="Root directory that contains H&E/ and Reticulin/ slide folders.",
    )
    parser.add_argument(
        "--metadata",
        type=Path,
        default=Path("metadata.csv"),
        help="Metadata CSV with source_ome and type columns.",
    )
    parser.add_argument(
        "--labels-root",
        type=Path,
        default=Path("outputs/yolo_masks/labels"),
        help="Directory where YOLO label txt files already exist or will be written.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=Path("outputs/yolo_dataset"),
        help="Destination folder for YOLO dataset layout.",
    )
    parser.add_argument(
        "--train-frac",
        type=float,
        default=0.8,
        help="Fraction of slides to place in the train split (rest go to val).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed used for splitting slides.",
    )
    parser.add_argument(
        "--generate-labels",
        action="store_true",
        help="Generate labels with generate_yolo_masks before wiring the dataset.",
    )
    parser.add_argument(
        "--downsample",
        type=float,
        default=0.1,
        help="Scale factor applied when saving PNGs (e.g., 0.1 -> 10% size).",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Optional limit on number of slides to include (for quick tests).",
    )
    return parser.parse_args()


def _ensure_labels(args: argparse.Namespace) -> None:
    if args.labels_root.exists() and any(args.labels_root.glob("**/*.txt")):
        return
    if not args.generate_labels:
        raise FileNotFoundError(
            f"No labels found under {args.labels_root}. "
            "Run with --generate-labels or point --labels-root to existing labels."
        )
    args.labels_root.mkdir(parents=True, exist_ok=True)
    build_masks(
        csv_path=args.metadata,
        output_root=args.labels_root.parent,
        class_mode="type",
        write_png=False,
    )


def _split_slides(df: pd.DataFrame, train_frac: float, seed: int, limit: int | None):
    slides = (
        df[["source_ome", "type"]]
        .drop_duplicates()
        .sample(frac=1.0, random_state=seed)
    )
    if limit:
        slides = slides.head(limit)
    train_cut = int(len(slides) * train_frac)
    train_df = slides.iloc[:train_cut]
    val_df = slides.iloc[train_cut:]
    return train_df, val_df


def _collect_label_map(labels_root: Path) -> Dict[Tuple[str, str], Path]:
    """
    Map (type_folder, slide_stem) -> label path.
    """
    mapping: Dict[Tuple[str, str], Path] = {}
    for txt in labels_root.glob("*/*.txt"):
        type_folder = txt.parent.name
        stem = txt.stem
        mapping[(type_folder, stem)] = txt
    return mapping


def _write_data_yaml(output_root: Path) -> None:
    data = {
        "path": str(output_root.resolve()),
        "train": "images/train",
        "val": "images/val",
        "names": {0: "he", 1: "reticulin"},
    }
    yaml_path = output_root / "data.yaml"
    import yaml  # Lazy import; PyYAML is commonly available with Ultralytics

    yaml_path.write_text(yaml.safe_dump(data, sort_keys=False))


def _downsample_to_png(src: Path, dest_png: Path, downsample: float) -> None:
    if downsample <= 0:
        raise ValueError("downsample must be > 0")
    dest_png.parent.mkdir(parents=True, exist_ok=True)

    with tifffile.TiffFile(src) as tif:
        arr = tif.series[0].asarray()

    if arr.ndim == 2:
        arr = np.repeat(arr[..., None], 3, axis=2)
    elif arr.ndim == 3 and arr.shape[2] > 3:
        arr = arr[..., :3]

    img = Image.fromarray(arr)
    if downsample != 1.0:
        new_w = max(1, int(img.width * downsample))
        new_h = max(1, int(img.height * downsample))
        img = img.resize((new_w, new_h), resample=Image.BILINEAR)

    img.save(dest_png, format="PNG")


def prepare_dataset(args: argparse.Namespace) -> None:
    _ensure_labels(args)
    df = pd.read_csv(args.metadata)
    train_df, val_df = _split_slides(df, args.train_frac, args.seed, args.limit)
    label_map = _collect_label_map(args.labels_root)

    def handle_split(split_df: pd.DataFrame, split_name: str) -> int:
        count = 0
        for _, row in tqdm(
            split_df.iterrows(),
            total=len(split_df),
            desc=f"{split_name} split",
            unit="slide",
        ):
            source_rel = Path(row["source_ome"])
            image_path = args.data_root / source_rel
            if not image_path.exists():
                raise FileNotFoundError(f"Missing image: {image_path}")

            type_folder = _type_folder(str(row["type"]))
            slide_stem = _clean_stem(image_path.name)
            label_key = (type_folder, slide_stem)
            if label_key not in label_map:
                raise FileNotFoundError(
                    f"No label found for slide {slide_stem} in {type_folder}"
                )

            dest_img = (
                args.output_root
                / "images"
                / split_name
                / type_folder
                / f"{slide_stem}.png"
            )
            dest_lbl = (
                args.output_root
                / "labels"
                / split_name
                / type_folder
                / f"{slide_stem}.txt"
            )

            _downsample_to_png(image_path, dest_img, args.downsample)
            dest_lbl.parent.mkdir(parents=True, exist_ok=True)
            if dest_lbl.exists():
                dest_lbl.unlink()
            dest_lbl.symlink_to(label_map[label_key].resolve())
            count += 1
        return count

    n_train = handle_split(train_df, "train")
    n_val = handle_split(val_df, "val")
    _write_data_yaml(args.output_root)
    print(
        f"Prepared YOLO dataset at {args.output_root} "
        f"(train: {n_train} slides, val: {n_val} slides)."
    )


def main() -> None:
    args = parse_args()
    prepare_dataset(args)


if __name__ == "__main__":
    main()
